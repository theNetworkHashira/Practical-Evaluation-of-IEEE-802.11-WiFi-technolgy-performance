"""
3D Visualisation of Wi‑Fi Frame Subtype Matrix
-----------------------------------------------
Reads the long‑format CSV generated by the matrix builder and produces an
interactive 3D scatter plot using Plotly.

Usage:
    python plot3d_matrix.py <long_csv_file>

Example:
    python plot3d_matrix.py S2_R31_01 - Copy_long.csv
"""

import sys
import pandas as pd
import plotly.express as px
import plotly.graph_objects as go
from plotly.offline import plot

# ================================================================
# ✏️  TWEAK THESE PARAMETERS
# ================================================================
MARKER_SIZE_SCALE = 10   # multiplier for marker size (count * scale)
OPACITY = 0.8            # marker transparency (0‑1)
PLOT_TITLE = "3D Scatter: Wi‑Fi Frame Subtypes over Time"
# ================================================================

def main(csv_file):
    # 1. Read the long CSV
    df = pd.read_csv(csv_file)
    
    # 2. Convert TimeBin (e.g., "0.0-0.1") to numeric start for proper ordering
    df['BinStart'] = df['TimeBin'].str.split('-').str[0].astype(float)
    
    # 3. Create the 3D scatter plot
    fig = px.scatter_3d(
        df,
        x='BinStart',
        y='Type/Subtype',
        z='Count',
        color='Hex',                # use the colour code
        color_discrete_map='identity',  # treat Hex as actual colour
        size='Count',
        size_max=20 * MARKER_SIZE_SCALE,
        opacity=OPACITY,
        hover_data={'Count': True, 'Percentage': ':.1f%', 'Hex': False},
        title=PLOT_TITLE,
        labels={
            'BinStart': 'Time (s)',
            'Type/Subtype': 'Frame Subtype',
            'Count': 'Packet Count'
        }
    )
    
    # 4. Improve the layout
    fig.update_layout(
        scene=dict(
            xaxis_title='Time (s)',
            yaxis_title='Frame Subtype',
            zaxis_title='Packet Count',
            xaxis=dict(tickmode='auto', nticks=20),
            yaxis=dict(tickfont=dict(size=10)),
            camera=dict(eye=dict(x=1.5, y=1.5, z=1.5))  # initial viewing angle
        ),
        width=1000,
        height=800,
        coloraxis_showscale=False  # we don't need a colour bar because colours are categorical from Hex
    )
    
    # 5. Save the figure as an interactive HTML file
    output_html = csv_file.replace('.csv', '_3d_scatter.html')
    fig.write_html(output_html)
    print(f"Interactive 3D plot saved to: {output_html}")
    
    # 6. Show the figure (if in a Jupyter notebook, it will display inline)
    fig.show()

if __name__ == "__main__":
    if len(sys.argv) < 2:
        print("Usage: python plot3d_matrix.py <long_csv_file>")
        sys.exit(1)
    
    csv_path = sys.argv[1]
    main(csv_path)